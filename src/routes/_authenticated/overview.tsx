import { createFileRoute, Link } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { useMemo } from "react";
import { Activity, Boxes, Cpu, Plus, Radar, Users } from "lucide-react";
import { analyticsEventsQuery, devicesQuery, roomsQuery, sensorsQuery } from "@/lib/data";
import { roomState, useLive } from "@/lib/radar/live";
import { deviceConnection, EVENT_LABELS } from "@/lib/radar/types";
import { occupancySessions, occupiedMs, utilisation } from "@/lib/analytics";
import { ConnBadge, Empty, Kpi, Panel, RoomBadge, SimTag, timeAgo } from "@/components/app/status";
import { EventRow } from "@/components/app/event-row";
import { AreaSeries, Bars } from "@/components/app/charts";
import { LD2450View } from "@/components/radar/ld2450-view";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";

export const Route = createFileRoute("/_authenticated/overview")({
  head: () => ({
    meta: [
      { title: "Overview — RoomTrace" },
      {
        name: "description",
        content: "Occupancy, targets and sensor health across your monitored spaces.",
      },
      { property: "og:title", content: "Overview — RoomTrace" },
      {
        property: "og:description",
        content: "Occupancy, targets and sensor health across your monitored spaces.",
      },
    ],
  }),
  component: Overview,
});

function greeting() {
  const h = new Date().getHours();
  return h < 12 ? "Good morning" : h < 18 ? "Good afternoon" : "Good evening";
}

function Overview() {
  const rooms = useQuery(roomsQuery);
  const devices = useQuery(devicesQuery);
  const sensors = useQuery(sensorsQuery);
  const live = useLive();
  const sim = live.mode === "simulation";
  const since = useMemo(() => new Date(Date.now() - 7 * 864e5).toISOString(), []);
  const hist = useQuery(analyticsEventsQuery(since, sim));

  const roomList = useMemo(() => rooms.data ?? [], [rooms.data]);
  const states = roomList.map((r) => ({
    r,
    s: roomState(live.frames[r.id], live.now, live.mode),
    f: live.frames[r.id],
  }));
  const occupied = states.filter((x) => x.s === "occupied").length;
  const targets = states.reduce(
    (n, x) => n + (x.s === "occupied" ? (x.f?.ld?.targets.length ?? 0) : 0),
    0,
  );
  const connDevices = (devices.data ?? []).filter(
    (d) => deviceConnection(d.last_seen, live.now) === "connected",
  ).length;

  const charts = useMemo(() => {
    const ev = hist.data ?? [];
    const now = Date.now();
    const sessions = occupancySessions(ev, now);
    const hourly = Array.from({ length: 24 }, (_, i) => {
      const from = now - (24 - i) * 3600e3;
      return {
        label: new Date(from + 3600e3).toLocaleTimeString([], { hour: "2-digit" }),
        minutes: Math.round(occupiedMs(sessions, from, from + 3600e3) / 60000),
      };
    });
    const daily = Array.from({ length: 7 }, (_, i) => {
      const d = new Date();
      d.setHours(0, 0, 0, 0);
      d.setDate(d.getDate() - (6 - i));
      const from = d.getTime();
      return {
        label: d.toLocaleDateString([], { weekday: "short" }),
        hours: +(occupiedMs(sessions, from, from + 864e5) / 3600e3).toFixed(1),
      };
    });
    const util = roomList.map((r) => ({
      label: r.name,
      pct: utilisation(sessions, now - 7 * 864e5, now, r.id),
    }));
    return { hourly, daily, util, has: sessions.length > 0 };
  }, [hist.data, roomList]);

  if (rooms.isLoading) return <OverviewSkeleton />;

  const roomName = (id: string) => roomList.find((r) => r.id === id)?.name;

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-2 sm:flex-row sm:items-end sm:justify-between">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">{greeting()}</h1>
          <p className="mt-1 text-sm text-muted-foreground">
            Here's what's happening in your monitored spaces.
          </p>
        </div>
        {sim && (
          <div className="flex items-center gap-2 text-xs text-muted-foreground">
            <SimTag /> Live metrics are generated by the simulation engine.
          </div>
        )}
      </div>

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <Kpi icon={<Boxes />} label="Total rooms" value={roomList.length} sub="Configured spaces" />
        <Kpi
          icon={<Users />}
          tone="primary"
          label="Occupied rooms"
          value={occupied}
          sub={`of ${roomList.length} rooms`}
          sim={sim}
          status={occupied > 0 ? "Active" : "Idle"}
        />
        <Kpi
          icon={<Radar />}
          tone="warning"
          label="Detected targets"
          value={targets}
          sub="LD2450, right now"
          sim={sim}
          status="Tracking"
        />
        <Kpi
          icon={<Cpu />}
          tone="success"
          label="Connected sensors"
          value={connDevices}
          sub={`${devices.data?.length ?? 0} ESP32-S3 registered`}
          status={connDevices > 0 ? "Online" : "Idle"}
          hint="Only counts devices that sent an authenticated heartbeat or telemetry in the last 60 s."
        />
      </div>

      {roomList.length === 0 ? (
        <Panel>
          <Empty
            icon={<Boxes className="size-5" />}
            title="No rooms configured yet"
            action={
              <Button asChild>
                <Link to="/rooms">
                  <Plus className="size-4" /> Add your first room
                </Link>
              </Button>
            }
          >
            Create a room with its dimensions to start the simulation and, later, assign your
            ESP32-S3 sensors.
          </Empty>
        </Panel>
      ) : (
        <div className="grid gap-6 xl:grid-cols-3">
          <Panel
            title="Room status"
            subtitle="Live target count per space"
            className="xl:col-span-2"
            action={
              <Link to="/rooms" className="text-xs font-medium text-primary hover:underline">
                Manage rooms
              </Link>
            }
          >
            <div className="grid gap-3 sm:grid-cols-2">
              {states.map(({ r, s, f }) => {
                const devs = (devices.data ?? []).filter((d) => d.room_id === r.id);
                return (
                  <Link
                    key={r.id}
                    to="/live"
                    onClick={() => live.setSelectedRoomId(r.id)}
                    className="group rounded-xl border bg-card p-4 transition-all hover:border-primary/40 hover:shadow-raised"
                  >
                    <div className="flex items-start justify-between gap-2">
                      <div>
                        <div className="font-medium">{r.name}</div>
                        <div className="text-xs text-muted-foreground">
                          {(r.width_mm / 1000).toFixed(1)} × {(r.length_mm / 1000).toFixed(1)} m
                        </div>
                      </div>
                      <RoomBadge s={s} />
                    </div>
                    <div className="mt-3 overflow-hidden rounded-lg">
                      <LD2450View
                        compact
                        widthMm={r.width_mm}
                        lengthMm={r.length_mm}
                        frame={f?.ld}
                        showTrails={false}
                        sweep={false}
                      />
                    </div>
                    <div className="mt-3 flex items-end justify-between">
                      <div>
                        <div className="font-mono text-2xl font-semibold tabular">
                          {s === "occupied" || s === "vacant" ? (f?.ld?.targets.length ?? 0) : "—"}
                        </div>
                        <div className="text-xs text-muted-foreground">targets</div>
                      </div>
                      <div className="text-right text-xs text-muted-foreground">
                        <div>
                          {sim
                            ? "Simulated sensor"
                            : devs.length
                              ? `${devs.length} device(s)`
                              : "No device assigned"}
                        </div>
                        <div>Updated {timeAgo(f?.ld?.timestamp, live.now)}</div>
                      </div>
                    </div>
                  </Link>
                );
              })}
            </div>
          </Panel>
          <Panel
            title={<>Live activity {sim && <SimTag />}</>}
            action={
              <Link to="/events" className="text-xs font-medium text-primary hover:underline">
                History
              </Link>
            }
          >
            {live.liveEvents.length === 0 ? (
              <Empty icon={<Activity className="size-5" />} title="Waiting for activity">
                {sim
                  ? "Events appear as simulated targets move."
                  : "Events appear when your hardware reports changes."}
              </Empty>
            ) : (
              <ol className="scroll-thin -my-2 max-h-[420px] space-y-0 overflow-auto px-1">
                {live.liveEvents.slice(0, 14).map((e) => (
                  <EventRow
                    key={e.id}
                    now={live.now}
                    event={{ ...e, label: EVENT_LABELS[e.event_type] }}
                    roomName={roomName(e.room_id)}
                  />
                ))}
              </ol>
            )}
          </Panel>
        </div>
      )}

      <div className="grid gap-6 lg:grid-cols-3">
        <Panel
          title={<>Hourly occupancy {sim && <SimTag />}</>}
          hint="Minutes per hour any room was occupied, from recorded occupied/vacant events (last 24 h)."
        >
          {charts.has ? (
            <AreaSeries data={charts.hourly} x="label" y="minutes" unit="m" />
          ) : (
            <NoHistory />
          )}
        </Panel>
        <Panel
          title={<>Daily occupancy {sim && <SimTag />}</>}
          hint="Total occupied hours per day across rooms (last 7 days)."
        >
          {charts.has ? (
            <Bars
              data={charts.daily}
              x="label"
              bars={[{ key: "hours", label: "Occupied", color: "var(--chart-1)" }]}
              unit="h"
            />
          ) : (
            <NoHistory />
          )}
        </Panel>
        <Panel
          title={<>Room utilisation {sim && <SimTag />}</>}
          hint="Share of the last 7 days each room was occupied."
        >
          {charts.has ? (
            <Bars
              data={charts.util}
              x="label"
              layout="vertical"
              bars={[{ key: "pct", label: "Utilisation", color: "var(--chart-2)" }]}
              unit="%"
            />
          ) : (
            <NoHistory />
          )}
        </Panel>
      </div>

      <Panel
        title="Sensor health"
        subtitle="Hardware status is only shown as connected after the backend receives authenticated telemetry."
        action={
          <Link to="/devices" className="text-xs font-medium text-primary hover:underline">
            Devices
          </Link>
        }
        bodyClass="p-0"
      >
        {(devices.data ?? []).length === 0 ? (
          <div className="p-5">
            <Empty
              icon={<Cpu className="size-5" />}
              title="No hardware registered"
              action={
                <Button variant="outline" asChild>
                  <Link to="/devices">Register ESP32-S3</Link>
                </Button>
              }
            >
              The simulation runs without hardware. Register a device when your ESP32-S3 is ready.
            </Empty>
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-sm">
              <thead className="bg-muted/40 text-left text-xs text-muted-foreground">
                <tr>
                  {["Device", "ESP32-S3", "LD2450", "RD-61", "Last telemetry"].map((h) => (
                    <th key={h} className="px-5 py-2.5 font-medium">
                      {h}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {(devices.data ?? []).map((d) => {
                  const ss = (sensors.data ?? []).filter((s) => s.device_id === d.id);
                  const c = deviceConnection(d.last_seen, live.now);
                  const sc = (t: string) => {
                    const s = ss.find((x) => x.sensor_type === t);
                    return s ? (
                      <ConnBadge
                        s={
                          c === "connected" && s.status === "connected"
                            ? "connected"
                            : c === "connected"
                              ? "unknown"
                              : c
                        }
                      />
                    ) : (
                      <span className="text-xs text-muted-foreground">Not fitted</span>
                    );
                  };
                  return (
                    <tr key={d.id} className="border-t transition-colors hover:bg-muted/40">
                      <td className="px-5 py-3 font-medium">
                        {d.device_name}
                        <div className="font-mono text-xs font-normal text-muted-foreground">
                          {d.device_id}
                        </div>
                      </td>
                      <td className="px-5">
                        <ConnBadge s={c} />
                      </td>
                      <td className="px-5">{sc("ld2450")}</td>
                      <td className="px-5">{sc("rd61")}</td>
                      <td className="px-5 text-muted-foreground">
                        {timeAgo(d.last_seen, live.now)}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </Panel>
    </div>
  );
}

function NoHistory() {
  return (
    <Empty icon={<Activity className="size-5" />} title="No history yet">
      Occupancy history builds up as rooms become occupied and vacant.
    </Empty>
  );
}

function OverviewSkeleton() {
  return (
    <div className="space-y-6">
      <Skeleton className="h-12 w-72" />
      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {[0, 1, 2, 3].map((i) => (
          <Skeleton key={i} className="h-36 rounded-xl" />
        ))}
      </div>
      <Skeleton className="h-72 rounded-xl" />
    </div>
  );
}
